export function articleBySlug(slug: string) {
  return articles.find((a) => a.slug === slug)
}

export function formatArticleDate(iso: string) {
  const [y, m, d] = iso.split('-')
  if (!y || !m || !d) return iso
  return `${d}.${m}.${y}`
}
