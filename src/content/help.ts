export function helpBySlug(slug: string) {
  return helpDocs.find((d) => d.slug === slug)
}

export function helpByGroup(group: HelpGroup) {
  return helpDocs.filter((d) => d.group === group)
}

export function searchHelp(q: string) {
  const s = q.trim().toLowerCase()
  if (!s) return helpDocs
  return helpDocs.filter((d) => `${d.title} ${d.dek} ${d.body.join(' ')}`.toLowerCase().includes(s))
}
