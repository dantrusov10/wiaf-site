export function getContest(slug: string) {
  return contests.find((c) => c.slug === slug)
}

export function formatContestDate(iso: string) {
  return new Intl.DateTimeFormat('ru-RU', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  }).format(new Date(`${iso}T12:00:00+03:00`))
}
